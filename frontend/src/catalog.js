const choice = (key, label, options) => ({
  key,
  label,
  type: "select",
  options,
});
const relation = (key, label, source) => ({
  key,
  label,
  type: "select",
  source,
});
const number = (key, label) => ({
  key,
  label,
  type: "number",
  min: 0.01,
  max: 99999999,
});
const date = (key, label) => ({ key, label, type: "date" });

