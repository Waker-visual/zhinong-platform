export function makeLetteringMarks(width,height) {
  const marks=[],right=18,top=24,sealSize=24,sealX=width-right-sealSize;
  const glyph=(text,x,y,cell,tone,part)=>{
    glyphs[text].forEach((row,r)=>{
      [...row].forEach((bit,c)=>{
        if(bit==='1')marks.push({x:x+c*cell,y:y+r*cell,char:(r+c)%3 ? '#' : ':',
          tone,size:cell,pixel:1,part});
      });
    });
  };
  // Fixed chips suggest a carved seal; they never flicker between frames.
  for(let i=0;i<sealSize;i++) {
    if(i!==5)marks.push({x:sealX+i,y:top,char:'#',tone:'sealInk',size:1,pixel:1,part:'seal'});
    if(i!==17)marks.push({x:sealX+i,y:top+sealSize-1,char:':',tone:'sealInk',size:1,pixel:1,part:'seal'});
    if(i!==7)marks.push({x:sealX,y:top+i,char:'#',tone:'sealInk',size:1,pixel:1,part:'seal'});
    if(i!==19)marks.push({x:sealX+sealSize-1,y:top+i,char:':',tone:'sealInk',size:1,pixel:1,part:'seal'});
  }
  // Traditional reading order: right column 李東, then left column 旭作.
  // Redrawn small glyphs keep the counters open when the 24 px seal is snapped to pixels.
  glyph('李',sealX+12,top+1,1,'sealInk','seal');
  glyph('東',sealX+12,top+12,1,'sealInk','seal');
  glyph('旭',sealX+1,top+1,1,'sealInk','seal');
  glyph('作',sealX+1,top+12,1,'sealInk','seal');
  const cell=1.25,titleX=sealX+(sealSize-16*cell)/2,titleTop=top+sealSize+9;
  [...'禾风水韵'].forEach((text,index)=>glyph(text,titleX,titleTop+index*25,cell,'letteringInk','title'));
  return marks.filter(mark=>mark.x>=0 && mark.y>=0 && mark.x<width && mark.y<height);
}
