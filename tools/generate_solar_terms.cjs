// lunar-javascript 1.7.7 provides astronomical term times in China Standard Time.
// Keep the library out of the browser bundle, as with generate_lunar_festivals.cjs.
const fs = require("node:fs");
const path = require("node:path");
const { Solar } = require("../frontend/node_modules/lunar-javascript");
const names =
  "小寒 大寒 立春 雨水 惊蛰 春分 清明 谷雨 立夏 小满 芒种 夏至 小暑 大暑 立秋 处暑 白露 秋分 寒露 霜降 立冬 小雪 大雪 冬至".split(
    " ",
  );
const rows = [];
for (let year = 2019; year <= 2051; year++) {
  const table = Solar.fromYmd(year, 6, 1).getLunar().getJieQiTable();
  rows.push(
    names.map((name) => {
      const date = table[name === "冬至" ? "DONG_ZHI" : name];
      if (date.getYear() !== year) throw Error(`Unexpected term year: ${name}`);
      return Date.parse(date.toYmdHms().replace(" ", "T") + "+08:00") / 1000;
    }),
  );
}
const output =
  "// Generated by tools/generate_solar_terms.cjs; lunar-javascript (MIT). Times are UTC seconds.\n" +
  "export const firstTermYear = 2019;\nexport const termTimes = " +
  JSON.stringify(rows) +
  ";\n";
const file = path.resolve(__dirname, "../frontend/src/ui/solar-term-times.js");
if (process.argv.includes("--check")) {
  if (fs.readFileSync(file, "utf8") !== output)
    throw Error("Solar term table is outdated");
  console.log("Solar term table verified (2019–2051).");
} else fs.writeFileSync(file, output);
